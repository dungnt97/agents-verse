// Local overlay maps keyed by Lang so useLandingInfoT() can resolve without
// touching AV_DICT / dictionary.ts.
const LOCAL: Record<'en' | 'vi', Record<string, string>> = { en, vi };

/**
 * Drop-in replacement for useI18n().t that first checks the local land/info
 * overlay before falling back to the global AV_DICT via the base t().
 */
export function useLandingInfoT() {
  const { lang, t: globalT } = useI18n();

  const t = (key: string): string => {
    const local = LOCAL[lang as 'en' | 'vi'];
    if (local && key in local) return local[key];
    return globalT(key);
  };

  return { t, lang };
}
